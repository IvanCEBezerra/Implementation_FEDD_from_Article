import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


BASE_DIR = Path(__file__).resolve().parent

DATA_DIR = BASE_DIR

OUTPUT_DIR = BASE_DIR / "figures"


def select_river_datasets(data_dir):
    """
    Select the univariate datasets generated by River.

    Expected files:
        <name>.npy
        <name>.json

    Feature matrices ending with "_X.npy" are ignored.
    """

    data_dir = Path(data_dir)

    datasets = []

    for path in sorted(
        data_dir.glob("friedman_*.npy")
    ):

        if path.stem.endswith("_X"):
            continue

        metadata_path = path.with_suffix(".json")

        if not metadata_path.exists():
            raise FileNotFoundError(
                f"Metadata not found: {metadata_path}"
            )

        with open(
            metadata_path,
            "r",
            encoding="utf-8"
        ) as file:
            metadata = json.load(file)

        datasets.append({
            "name": path.stem,
            "path": path,
            "drift_type": metadata["drift_type"],
            "drift_kind": metadata["drift_kind"],
            "true_drifts": metadata["positions"],
            "transition_window": metadata.get(
                "transition_window"
            ),
            "seed": metadata["seed"],
        })

    return datasets


def plot_single_series(
    dataset,
    output_dir,
    show_transition_window=True,
):
    """
    Plot one River-generated time series.

    True drift positions are shown as red dashed vertical lines.

    For gradual drift datasets, the transition interval can
    also be displayed as a shaded region.
    """

    output_dir = Path(output_dir)

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    series = np.load(
        dataset["path"]
    )

    time = np.arange(
        len(series)
    )

    figure, axis = plt.subplots(
        figsize=(12, 4)
    )

    axis.plot(
        time,
        series,
        linewidth=0.7,
    )

    drift_label_added = False
    transition_label_added = False

    for drift in dataset["true_drifts"]:

        if not drift_label_added:

            axis.axvline(
                x=drift,
                color="red",
                linestyle="--",
                linewidth=1.2,
                label="Concept drift",
            )

            drift_label_added = True

        else:

            axis.axvline(
                x=drift,
                color="red",
                linestyle="--",
                linewidth=1.2,
            )

        if (
            dataset["drift_kind"] == "gradual"
            and show_transition_window
            and dataset["transition_window"] is not None
        ):

            half_window = (
                dataset["transition_window"]
                / 2
            )

            transition_start = (
                drift - half_window
            )

            transition_end = (
                drift + half_window
            )

            if not transition_label_added:

                axis.axvspan(
                    transition_start,
                    transition_end,
                    color="red",
                    alpha=0.10,
                    label="Transition window",
                )

                transition_label_added = True

            else:

                axis.axvspan(
                    transition_start,
                    transition_end,
                    color="red",
                    alpha=0.10,
                )

    axis.set_xlabel(
        "Time"
    )

    axis.set_ylabel(
        "Value"
    )

    axis.set_title(
        f"{dataset['name']} - "
        f"{dataset['drift_kind'].capitalize()} drift"
    )

    axis.grid(
        axis="y",
        linestyle=":",
        linewidth=0.5,
        alpha=0.6,
    )

    axis.legend(
        loc="upper right",
        fontsize=8,
    )

    figure.tight_layout()

    output_path = (
        output_dir
        / f"{dataset['name']}_series.png"
    )

    figure.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(
        figure
    )

    return output_path


def plot_all_series(
    data_dir,
    output_dir,
    max_per_kind=1,
    show_transition_window=True,
):
    """
    Plot datasets generated by River.

    Parameters
    ----------
    max_per_kind
        Maximum number of series plotted for each drift kind.

        Example:
            1 -> one abrupt and one gradual series
            3 -> three abrupt and three gradual series
            None -> all datasets

    show_transition_window
        If True, gradual datasets show their transition interval.
    """

    datasets = select_river_datasets(
        data_dir
    )

    counters = {
        "abrupt": 0,
        "gradual": 0,
    }

    saved_paths = []

    for dataset in datasets:

        drift_kind = dataset[
            "drift_kind"
        ]

        if (
            max_per_kind is not None
            and counters.get(
                drift_kind,
                0
            ) >= max_per_kind
        ):
            continue

        output_path = plot_single_series(
            dataset=dataset,
            output_dir=output_dir,
            show_transition_window=show_transition_window,
        )

        saved_paths.append(
            output_path
        )

        counters[drift_kind] = (
            counters.get(
                drift_kind,
                0
            )
            + 1
        )

    return saved_paths


def main():
    """
    Generate representative time-series plots
    for the FriedmanDrift datasets.
    """

    saved_paths = plot_all_series(
        data_dir=DATA_DIR,
        output_dir=OUTPUT_DIR,
        max_per_kind=1,
        show_transition_window=True,
    )

    print(
        "Plots generated:",
        len(saved_paths)
    )

    for path in saved_paths:
        print(
            "Saved:",
            path
        )


if __name__ == "__main__":
    main()