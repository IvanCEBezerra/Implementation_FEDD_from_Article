def save_results(
    results,
    output_path
):
    """
    Save detector results as a NumPy object array.
    """

    output_path = Path(output_path)

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    np.save(
        output_path,
        np.asarray(
            results,
            dtype=object
        ),
        allow_pickle=True
    )


def save_metadata(
    dataset,
    output_path
):
    """
    Save the dataset ground truth together with
    the experiment results.
    """

    output_path = Path(output_path)

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    metadata = {
        "name": dataset["name"],
        "drift_type": dataset["drift_type"],
        "drift_kind": dataset["drift_kind"],
        "true_drifts": dataset["true_drifts"],
        "transition_window":
            dataset["transition_window"],
        "seed": dataset["seed"],
    }

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            metadata,
            file,
            indent=2
        )