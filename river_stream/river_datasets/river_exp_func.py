import json

from pathlib import Path

import numpy as np

from fedd.drift_detection.detector import FEDDDetector
from fedd.drift_detection.elm_ecdd import ELM_ECDD_Detector
from river_stream.exp_base.vector_stream import vector_stream


def select_river_datasets(data_dir):
    """
    Select the univariate datasets generated by River.

    Each dataset must contain:

        <name>.npy
        <name>.json

    Feature matrices ending in "_X.npy" are ignored.
    """

    data_dir = Path(data_dir)

    datasets = []

    for path in sorted(data_dir.glob("friedman_*.npy")):

        if path.stem.endswith("_X"):
            continue

        metadata_path = path.with_suffix(".json")

        if not metadata_path.exists():
            raise FileNotFoundError(
                f"Metadata not found: {metadata_path}"
            )

        with open(
            metadata_path,
            "r",
            encoding="utf-8"
        ) as file:
            metadata = json.load(file)

        datasets.append({
            "name": path.stem,
            "path": path,
            "drift_type": metadata["drift_type"],
            "drift_kind": metadata["drift_kind"],
            "true_drifts": metadata["positions"],
            "transition_window": metadata.get(
                "transition_window"
            ),
            "seed": metadata["seed"],
        })

    return datasets


def run_fedd_experiment(
    vector,
    distance="cosine"
):
    """
    Run FEDD on a univariate stream.
    """

    detector = FEDDDetector(
        distance=distance
    )

    datastream = vector_stream(
        vector
    )

    results = []

    for observation in datastream:

        value = observation[0][0]

        result = detector.update(
            value
        )

        results.append(result)

    return results


